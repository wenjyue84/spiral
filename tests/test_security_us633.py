"""Security tests for SPIRAL Phase Loop: No credential leakage in state files (US-707).

Verifies that the SPIRAL phase loop (R→T→S→M→I→V→C) does not leak API keys,
tokens, or passwords into intermediate state files:
- _research_output.json
- _validated_stories.json
- _checkpoint.json
- results.tsv

Also verifies that phase transition errors do not expose secrets in log output.
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))


# ─────────────────────────────────────────────────────────────────────────────
# Credential Pattern Matchers
# ─────────────────────────────────────────────────────────────────────────────

CREDENTIAL_PATTERNS = {
    "anthropic_api_key": r"sk-ant-[a-zA-Z0-9_-]{20,}",
    "gemini_api_key": r"AIzaSy[a-zA-Z0-9_-]{34}",
    "bearer_token": r"bearer\s+[a-zA-Z0-9_-]{20,}",
    "password_assignment": r"password[\":\s]*[=:]\s*['\"]?[^\s'\"]+['\"]?",
    "api_key_assignment": r"api[_-]?key\s*[=:]\s*['\"]?[^\s'\"]+['\"]?",
    "auth_header": r"Authorization:\s*[^\s]+",
}

DUMMY_SECRETS = {
    "ANTHROPIC_API_KEY": "sk-ant-test-1234567890abcdefghij",
    "GEMINI_API_KEY": "AIzaSyTestGeminiKeyWithExactLengthXYZ12345",
    "SPIRAL_API_BEARER": "bearer-test-token-abcdefghijk",
    "DB_PASSWORD": "test_password_secret_123",
}


