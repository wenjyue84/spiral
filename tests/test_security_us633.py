# Helper Functions
# ─────────────────────────────────────────────────────────────────────────────


def _find_credentials_in_text(text: str) -> list[tuple[str, str]]:
    """Find all matching credentials in text.

    Returns: list of (pattern_name, matched_text) tuples.
    """
    found = []
    for pattern_name, pattern in CREDENTIAL_PATTERNS.items():
        matches = re.finditer(pattern, text, re.IGNORECASE)
        for match in matches:
            found.append((pattern_name, match.group(0)))
    return found


def _check_file_for_credentials(file_path: Path | str) -> list[tuple[str, str]]:
    """Read file and search for credential patterns.

    Returns: list of (pattern_name, matched_text) tuples.
    """
    file_path = Path(file_path)
    if not file_path.exists():
        return []

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            content = f.read()
    except Exception:
        # If file can't be read, skip it
        return []

    return _find_credentials_in_text(content)


def _check_json_file_for_secrets(file_path: Path | str) -> list[str]:
    """Load JSON file and check all values for dummy secret strings.

    Returns: list of found secret values.
    """
    file_path = Path(file_path)
    if not file_path.exists():
        return []

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return []

    secrets_found = []
    json_str = json.dumps(data)

    for secret_name, secret_value in DUMMY_SECRETS.items():
        if secret_value in json_str:
            secrets_found.append(f"{secret_name}: {secret_value}")

    return secrets_found


def _check_tsv_for_secrets(file_path: Path | str) -> list[str]:
    """Read TSV file and check for dummy secret strings.

    Returns: list of found secret values.
    """
    file_path = Path(file_path)
    if not file_path.exists():
        return []

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            content = f.read()
    except Exception:
        return []

    secrets_found = []
    for secret_name, secret_value in DUMMY_SECRETS.items():
        if secret_value in content:
            secrets_found.append(f"{secret_name}: {secret_value}")

    return secrets_found


