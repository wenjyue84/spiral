class TestNoCredentialsInStateFiles:
    """Verify that state files do not contain credential patterns."""

    def test_no_credentials_in_state_files(self, monkeypatch: Any) -> None:
        """Verify SPIRAL state files don't leak secrets.

        Test approach:
        1. Create temporary .spiral/ directory
        2. Monkeypatch environment with dummy secrets
        3. Create mock state files as if generated by phase helpers
        4. Assert no credentials appear in any state file
        """
        with tempfile.TemporaryDirectory() as tmpdir:
            spiral_dir = Path(tmpdir) / ".spiral"
            spiral_dir.mkdir()

            # Inject dummy secrets into environment
            for secret_name, secret_value in DUMMY_SECRETS.items():
                monkeypatch.setenv(secret_name, secret_value)

            # Create mock _research_output.json (from Phase R)
            research_data = {
                "candidates": [
                    {
                        "id": "US-001",
                        "title": "Test story",
                        "description": "A test story",
                        "source": "research",
                        "evidence": "Web search result",
                    }
                ],
                "timestamp": "2026-03-22T00:00:00Z",
            }
            research_file = spiral_dir / "_research_output.json"
            with open(research_file, "w", encoding="utf-8") as f:
                json.dump(research_data, f)

            # Create mock _validated_stories.json (from Phase S)
            validated_data = {
                "accepted": [
                    {
                        "id": "US-001",
                        "title": "Test story",
                        "reason": "Aligns with constitution",
                    }
                ],
                "rejected": [],
            }
            validated_file = spiral_dir / "_validated_stories.json"
            with open(validated_file, "w", encoding="utf-8") as f:
                json.dump(validated_data, f)

            # Create mock _checkpoint.json (from Phase I)
            checkpoint_data = {
                "iteration": 1,
                "phase": "I",
                "timestamp": "2026-03-22T00:00:00Z",
                "status": "in_progress",
            }
            checkpoint_file = spiral_dir / "_checkpoint.json"
            with open(checkpoint_file, "w", encoding="utf-8") as f:
                json.dump(checkpoint_data, f)

            # Create mock results.tsv (from Phase V)
            results_file = spiral_dir / "results.tsv"
            with open(results_file, "w", encoding="utf-8") as f:
                f.write("story_id\tstatus\tmodel\tduration_sec\n")
                f.write("US-001\tpassed\thaiku\t10\n")

            # Check all state files for dummy secrets
            research_secrets = _check_json_file_for_secrets(research_file)
            validated_secrets = _check_json_file_for_secrets(validated_file)
            checkpoint_secrets = _check_json_file_for_secrets(checkpoint_file)
            results_secrets = _check_tsv_for_secrets(results_file)

            # Assert no secrets leaked
            assert not research_secrets, f"Found secrets in _research_output.json: {research_secrets}"
            assert not validated_secrets, f"Found secrets in _validated_stories.json: {validated_secrets}"
            assert not checkpoint_secrets, f"Found secrets in _checkpoint.json: {checkpoint_secrets}"
            assert not results_secrets, f"Found secrets in results.tsv: {results_secrets}"

    def test_no_anthropic_api_key_in_state(self, monkeypatch: Any) -> None:
        """Verify ANTHROPIC_API_KEY never appears in state files."""
        with tempfile.TemporaryDirectory() as tmpdir:
            spiral_dir = Path(tmpdir) / ".spiral"
            spiral_dir.mkdir()

            # Inject Anthropic key
            test_key = "sk-ant-test-1234567890abcdefghij"
            monkeypatch.setenv("ANTHROPIC_API_KEY", test_key)

            # Create a file that should NOT contain the key
            state_file = spiral_dir / "test_state.json"
            test_data = {
                "stories": ["US-001"],
                "config": {"key_prefix": "sk-ant"},  # Safe: just a string, not the key
            }
            with open(state_file, "w", encoding="utf-8") as f:
                json.dump(test_data, f)

            # Verify the actual key doesn't appear
            with open(state_file, "r", encoding="utf-8") as f:
                content = f.read()

            assert test_key not in content, f"API key leaked: {test_key}"

    def test_no_gemini_key_in_state(self, monkeypatch: Any) -> None:
        """Verify GEMINI_API_KEY never appears in state files."""
        with tempfile.TemporaryDirectory() as tmpdir:
            spiral_dir = Path(tmpdir) / ".spiral"
            spiral_dir.mkdir()

            # Inject Gemini key
            test_key = "AIzaSyTestGeminiKeyWithExactLengthXYZ12345"
            monkeypatch.setenv("GEMINI_API_KEY", test_key)

            state_file = spiral_dir / "test_state.json"
            test_data = {
                "research_backend": "gemini",
                "api": "AIzaSy...",  # Safe: redacted reference
            }
            with open(state_file, "w", encoding="utf-8") as f:
                json.dump(test_data, f)

            with open(state_file, "r", encoding="utf-8") as f:
                content = f.read()

            assert test_key not in content, f"Gemini key leaked: {test_key}"


class TestNoCredentialsInErrorOutput:
    """Verify that error messages and logs don't expose secrets."""

    def test_error_output_no_api_key(self, monkeypatch: Any, capsys: Any) -> None:
        """Verify error messages don't leak API keys.

        Test approach:
        1. Set environment with dummy secret
        2. Simulate an error scenario
        3. Capture stderr/stdout
        4. Assert no credentials in captured output
        """
        test_key = "sk-ant-test-1234567890abcdefghij"
        monkeypatch.setenv("ANTHROPIC_API_KEY", test_key)

        # Simulate an error that might naively expose the env var
        error_context = {"ANTHROPIC_API_KEY": test_key}
        error_msg = "Phase R failed with context"

        # Safe error message (should not include the actual key)
        safe_error = f"{error_msg}: API key validation failed"

        # Capture if we were to print unsafe message
        # (we won't actually print it, but verify pattern detection works)
        unsafe_error = f"{error_msg}: {error_context}"

        # Check that safe message doesn't contain key
        assert test_key not in safe_error

        # Verify pattern detector would catch unsafe version
        patterns_found = _find_credentials_in_text(unsafe_error)
        assert len(patterns_found) > 0, "Pattern detector should find the key"

    def test_exception_traceback_no_secrets(self, monkeypatch: Any) -> None:
        """Verify exception tracebacks don't expose secrets.

        When an exception occurs during phase execution, the traceback
        should not include actual credential values.
        """
        test_key = "sk-ant-test-1234567890abcdefghij"
        monkeypatch.setenv("ANTHROPIC_API_KEY", test_key)

        # Simulate a mock exception that occurred during phase execution
        try:
            # This code path would normally load the API key from env
            api_key = os.environ.get("ANTHROPIC_API_KEY")

            # Simulate error in phase helper (but don't expose key in error)
            if not api_key:
                raise ValueError("ANTHROPIC_API_KEY not set")

            # Safely format error without exposing the key
            error_context = {
                "phase": "R",
                "status": "failed",
                "reason": "Authentication failed",
            }
            raise RuntimeError(f"Phase error: {error_context}")

        except RuntimeError as e:
            error_text = str(e)

            # Verify the actual key is not in the error message
            assert test_key not in error_text, f"API key exposed in error: {error_text}"

    def test_log_output_no_password_leakage(self, monkeypatch: Any) -> None:
        """Verify log messages don't contain password values."""
        test_password = "test_password_secret_123"
        monkeypatch.setenv("DB_PASSWORD", test_password)

        # Simulate a safe log message (redacted)
        safe_log = "Connecting to database with credentials from environment"

        # Verify safe log doesn't contain the actual password
        assert test_password not in safe_log

        # Verify pattern matcher would catch unsafe log
        unsafe_log = f"DB connection string: password={test_password}"
        patterns = _find_credentials_in_text(unsafe_log)
        assert len(patterns) > 0, "Should detect password assignment pattern"

    def test_phase_error_doesnt_expose_bearer_token(self, monkeypatch: Any) -> None:
        """Verify phase errors don't expose bearer tokens."""
        test_token = "bearer-test-token-abcdefghijk"
        monkeypatch.setenv("SPIRAL_API_BEARER", test_token)

        # Safe error message
        safe_error = "API request failed with 401 Unauthorized"
        assert test_token not in safe_error

        # Unsafe version would be caught
        unsafe_error = f"Failed: {test_token}"
        assert test_token in unsafe_error


class TestCredentialPatternDetection:
    """Test the credential pattern matcher itself."""

    def test_detect_anthropic_key_pattern(self) -> None:
        """Verify we can detect Anthropic API key patterns."""
        text = "Authorization: sk-ant-1234567890abcdefghij"
        patterns = _find_credentials_in_text(text)
        assert len(patterns) > 0
        assert any(p[0] == "anthropic_api_key" for p in patterns)

    def test_detect_password_assignment_pattern(self) -> None:
        """Verify we can detect password= assignments."""
        text = 'config = {"password": "secret123"}'
        patterns = _find_credentials_in_text(text)
        assert len(patterns) > 0
        assert any(p[0] == "password_assignment" for p in patterns), f"Expected password pattern, got {patterns}"

    def test_no_false_positives_on_safe_text(self) -> None:
        """Verify safe text doesn't trigger false positives."""
        safe_texts = [
            "The API is located at https://api.example.com",
            "Bearer tokens expire after 24 hours",
            "We use password hashing algorithms",
            "Authentication header format: Authorization: <token>",
        ]
        for text in safe_texts:
            patterns = _find_credentials_in_text(text)
            # Some might match "Bearer" or "password" in non-credential context
            # but should not match full actual secret patterns
            for pattern_name, _ in patterns:
                if pattern_name in ["anthropic_api_key", "gemini_api_key"]:
                    pytest.fail(f"False positive for {pattern_name} in: {text}")


